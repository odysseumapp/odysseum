import { test, expect, type APIRequestContext } from '@playwright/test'
import { readFile, writeFile, mkdir, unlink, access } from 'node:fs/promises'
import path from 'node:path'
import type { DocumentContent, Project } from '../src/models'

// The test workspace is seeded with the demo project on first start; every project is one folder inside it.
const workspaceRoot = path.resolve('../.test-data/browser')
const projectSlug = 'Sample manuscript'
const projectUrl = `/p/${encodeURIComponent(projectSlug)}`
const apiBase = `/api/projects/${encodeURIComponent(projectSlug)}`
const fixtureRoot = path.join(workspaceRoot, projectSlug)
const title = (prefix: string) => `${prefix} ${Date.now()}`
async function create(request: APIRequestContext, name: string, content: string) {
  const response = await request.post(`${apiBase}/documents`, { data: { title: name, folder: 'Manuscript/Browser checks', content } })
  expect(response.ok()).toBeTruthy()
  return (await response.json()).data as DocumentContent
}
// API responses are enveloped as { apiVersion, data }.
async function getProject(request: APIRequestContext) {
  return (await (await request.get(apiBase)).json()).data as Project
}

