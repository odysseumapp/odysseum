test('keeps a browser draft when an external edit conflicts', async ({ page, request }) => {
  const name = title('Conflicting scene')
  const doc = await create(request, name, 'Original paragraph.')
  await page.goto(projectUrl)
  await page.getByRole('button', { name, exact: true }).click()
  const editor = page.getByRole('textbox', { name: 'Manuscript editor' })
  await expect(editor).toContainText('Original paragraph.')
  const file = path.join(fixtureRoot, doc.document.path)
  const raw = await readFile(file, 'utf8')
  // Delay saves so the independent filesystem edit is guaranteed to win this race.
  await page.route(`**${apiBase}/documents/${doc.document.id}`, async route => {
    if (route.request().method() === 'PUT') await new Promise(resolve => setTimeout(resolve, 500))
    await route.continue()
  })
  await editor.fill('My browser draft must survive.')
  await writeFile(file, raw.replace('Original paragraph.', 'The version from my other editor.'))
  // The footer save indicator also reads "Review changes" during a conflict, so scope to the notice bar.
  const review = page.locator('.notice-bar').getByRole('button', { name: 'Review changes', exact: true })
  await expect(review).toBeVisible()
  await expect(editor).toContainText('My browser draft must survive.')
  expect(await readFile(file, 'utf8')).toContain('The version from my other editor.')
  await review.click()
  await expect(page.getByRole('textbox', { name: 'Your browser draft' })).toHaveValue('My browser draft must survive.')
  await expect(page.locator('.conflict-columns pre')).toContainText('The version from my other editor.')
  await page.getByRole('button', { name: 'Save my version', exact: true }).click()
  await expect(page.getByRole('button', { name: 'All changes saved', exact: true })).toBeVisible()
  expect(await readFile(file, 'utf8')).toContain('My browser draft must survive.')
})

test('keeps an edit made while saves fail and syncs it once they succeed', async ({ page, request }) => {
  const name = title('Recovered scene')
  const doc = await create(request, name, 'Saved beginning.')
  await page.goto(projectUrl)
  await page.getByRole('button', { name, exact: true }).click()
  const editor = page.getByRole('textbox', { name: 'Manuscript editor' })
  await expect(editor).toContainText('Saved beginning.')
  await page.route(`**${apiBase}/documents/${doc.document.id}`, route => route.request().method() === 'PUT' ? route.abort() : route.continue())
  await editor.fill('An unsaved thought worth keeping.')
  await expect(page.getByRole('button', { name: 'Saved on this device', exact: true })).toBeVisible()
  await expect(page.getByText(/1 change waiting/)).toBeVisible()
  await page.reload()
  await expect(editor).toContainText('An unsaved thought worth keeping.')
  await page.unroute(`**${apiBase}/documents/${doc.document.id}`)
  // No button, no keystroke: the engine retries on its own.
  await expect(page.getByRole('button', { name: 'All changes saved', exact: true })).toBeVisible({ timeout: 15000 })
  expect(await readFile(path.join(fixtureRoot, doc.document.path), 'utf8')).toContain('An unsaved thought worth keeping.')
})

